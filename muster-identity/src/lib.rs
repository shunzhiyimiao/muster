//! # muster-identity — 身份与权限语义内核(任务 P2)
//!
//! 一句话:**先把"谁能做什么"做成可穷举验证的纯函数,再谈它从哪来。**
//!
//! ## 为什么先做语义内核而不是先搭服务器
//!
//! 总规划 P2 的完整形态是 Axum + PostgreSQL + Keycloak 的中心服务器。但那是
//! **部署形态**,不是权限语义本身。先上服务器会让「个人本地版」(§1.3 明确
//! 要支持)凭空变重,而且在没有第二个用户之前,那些代码无从验证。
//!
//! 反过来,§4.4 的「权限计算顺序」本身就是一个纯函数,与 E2 的
//! `decide()` 同构:无 IO、无时钟,可以穷举全部输入组合验证不变量。做完它,
//! 审批流的"谁有资格裁决"才有依据;日后接 OIDC 只是**换掉 Principal 的来源**,
//! 判定逻辑一行不用改。
//!
//! ## 五条不变量(穷举验证,`tests/matrix.rs`)
//!
//! - **I1 组织级禁止不可推翻**:冻结写操作时,连 OrgOwner 也写不了。
//! - **I2 作用域不可越界**:某组的 GroupAdmin 管不到别的组;Channel 级授权
//!   不会向上放大成组级。
//! - **I3 裁决必须由人做出**:Agent 与服务账号永远不能 `ApproveMerge`——
//!   否则 P5 审批就成了 Agent 自批自的形式主义。
//! - **I4 服务账号不能登录 UI**(§4.3),这是身份属性不是策略取值。
//! - **I5 判定是确定性纯函数**:同输入必同输出。
//!
//! ## 拒绝必须带理由,且分层
//!
//! [`Decision::Deny`] 带 `layer`,区分"组织策略挡的"/"角色不够"/"作用域没覆盖"
//! ——三者的解法完全不同(等策略解冻 / 申请角色 / 扩大授权范围),
//! 只说"没有权限"对使用者毫无帮助。

